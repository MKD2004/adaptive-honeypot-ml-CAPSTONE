export function getCveById(cveId) {
  return mockCves.find((c) => c.cve_id === cveId)
}

// Summary counts for the page's summary cards — all computed from the
// sample array above, not separately hardcoded, so they can never drift
// from what the table actually shows.
export const TOTAL_CVES = mockCves.length
export const CRITICAL_CVE_COUNT = mockCves.filter((c) => c.severity === 'Critical').length
export const HIGH_CVE_COUNT = mockCves.filter((c) => c.severity === 'High').length

// "Recent" is defined relative to the SAMPLE's own most recent
// last_modified timestamp, not the browser's real current date — these are
// 2026-era snapshot dates, so anchoring to real "today" would make this
// metric read as 0 long after the snapshot was taken. This still honestly
// answers "which of these 45 records were touched most recently in this
// sample," it just doesn't pretend the sample is continuously refreshed.
const RECENT_WINDOW_DAYS = 14
const maxLastModified = Math.max(...mockCves.map((c) => new Date(c.last_modified).getTime()))
export const RECENT_CVE_COUNT = mockCves.filter(
  (c) => maxLastModified - new Date(c.last_modified).getTime() <= RECENT_WINDOW_DAYS * 86400000,
).length
export const RECENT_WINDOW_LABEL = `within the sample's most recent ${RECENT_WINDOW_DAYS} days`

